def test_evaluate_retrieval_reports_recall_and_mrr_without_content(chunks):
    retriever = real_corpus_retriever.GovernedChunkBM25Retriever(chunks)
    cases = [
        {
            "id": "warm-reset",
            "query": "6.9.3 Warm Reset",
            "allowed_source_ids": ["usb32"],
            "target": {
                "source_id": "usb32",
                "section": "6.9.3",
                "page_or_anchor": "p.135",
            },
        },
        {
            "id": "usb2-suspend",
            "query": "hub suspend resume state",
            "allowed_source_ids": ["usb20_se"],
            "target": {"source_id": "usb20_se", "chapter": "7"},
        },
    ]

    summary = evaluate_retrieval(retriever, cases, top_k=3)

    assert summary["queries_evaluated"] == 2
    assert summary["recall@1"] == 100.0
    assert summary["recall@3"] == 100.0
    assert summary["recall@5"] == 100.0
    assert summary["mrr"] == 1.0
    assert [row["target_rank"] for row in summary["cases"]] == [1, 1]
    assert all(
        "content" not in hit
        for row in summary["cases"]
        for hit in row["top_hits"]
    )


def test_selector_targets_distinguish_same_metadata_chunks():
    power = _chunk(
        source_id="usb32",
        section="10.16.2.10",
        page="p.483",
        content="PORT_POWER feature selector value is 8.",
        index=10,
    )
    link_state = _chunk(
        source_id="usb32",
        section="10.16.2.10",
        page="p.483",
        content="PORT_LINK_STATE feature selector value is 5.",
        index=11,
    )
    retriever = real_corpus_retriever.GovernedChunkBM25Retriever(
        [power, link_state]
    )
    cases = [
        {
            "id": "power",
            "query": "PORT_POWER feature selector value",
            "allowed_source_ids": ["usb32"],
            "target": {"chunk_id": power.chunk_id},
        },
        {
            "id": "link-state",
            "query": "PORT_LINK_STATE feature selector value",
            "allowed_source_ids": ["usb32"],
            "target": {"chunk_id": link_state.chunk_id},
        },
    ]

    summary = evaluate_retrieval(retriever, cases, top_k=1)

    assert [row["target_rank"] for row in summary["cases"]] == [1, 1]
    assert [
        row["top_hits"][0]["chunk_id"] for row in summary["cases"]
    ] == [power.chunk_id, link_state.chunk_id]


