def test_query_returns_ranked_governed_chunks_with_provenance(chunks):
    retriever = real_corpus_retriever.GovernedChunkBM25Retriever(chunks)

    hits = retriever.query("6.9.3 Warm Reset", top_k=3)

    assert hits
    assert any(
        hit.chunk.source_id == "usb32"
        and hit.chunk.section == "6.9.3"
        and hit.chunk.page_or_anchor == "p.135"
        for hit in hits
    )
    assert hits[0].score > 0
    assert "warm" in hits[0].matched_terms
    assert hits[0].chunk.to_citation().evidence_id == hits[0].chunk.chunk_id



def test_query_uses_section_caption_context_to_find_table_chunk(chunks):
    retriever = real_corpus_retriever.GovernedChunkBM25Retriever(chunks)

    hits = retriever.query("Table 6-30 LFPS Transmitter Timing", top_k=5)

    table_hits = [hit for hit in hits if hit.chunk.chunk_kind == "table"]
    assert table_hits
    assert table_hits[0].chunk.source_id == "usb32"
    assert table_hits[0].chunk.section == "6.9.1"
    assert table_hits[0].chunk.page_or_anchor == "p.131"



