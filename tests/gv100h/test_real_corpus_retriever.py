def test_retrieval_is_deterministic_for_same_chunk_sequence(chunks):
    first = real_corpus_retriever.GovernedChunkBM25Retriever(chunks)
    second = real_corpus_retriever.GovernedChunkBM25Retriever(chunks)

    first_records = [hit.as_record() for hit in first.query("Warm Reset", top_k=5)]
    second_records = [hit.as_record() for hit in second.query("Warm Reset", top_k=5)]

    assert first.corpus_sha256 == second.corpus_sha256
    assert first_records == second_records



