def test_from_corpus_lock_loads_chunks_through_existing_ingestion_loader(
    chunks, monkeypatch, tmp_path
):
    calls = {}

    def fake_load(source_ids, corpus_lock, *, raw_root):
        calls["source_ids"] = tuple(source_ids)
        calls["corpus_lock"] = corpus_lock
        calls["raw_root"] = raw_root
        return chunks

    monkeypatch.setattr(real_corpus_retriever, "load_accepted_chunks", fake_load)
    lock = {"sources": {"usb32": {"layer": "official_raw"}}}

    retriever = real_corpus_retriever.GovernedChunkBM25Retriever.from_corpus_lock(
        lock,
        source_ids=("usb32",),
        raw_root=tmp_path,
    )

    assert len(retriever) == len(chunks)
    assert calls == {
        "source_ids": ("usb32",),
        "corpus_lock": lock,
        "raw_root": tmp_path,
    }


