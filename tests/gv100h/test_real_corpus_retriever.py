def _chunk(
    *,
    source_id: str,
    section: str,
    page: str,
    content: str,
    kind: str = "paragraph",
    index: int = 0,
) -> GovernedChunk:
    return GovernedChunk.build(
        source_id=source_id,
        document=(
            "USB 3.2 Specification"
            if source_id == "usb32"
            else "USB 2.0 Specification"
        ),
        revision="Rev 1.1" if source_id == "usb32" else "2.0",
        section=section,
        page_or_anchor=page,
        authority_level="authoritative",
        chunk_kind=kind,
        content=content,
        index=index,
    )


